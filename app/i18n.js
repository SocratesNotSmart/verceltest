export const VOICE_LOCALE = { lt: 'lt-LT', en: 'en-GB', it: 'it-IT' };

let current = 'lt';

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'lt';
  return current;
}

export function getLang() {
  return current;
}

export function t(key, ...args) {
  const value = STRINGS[current]?.[key] ?? STRINGS.lt[key] ?? key;
  return typeof value === 'function' ? value(...args) : value;
}
